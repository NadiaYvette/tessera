(* Tessera — SSG-3: the interrupt controller (intc.sail) realizes the IPI
   mailbox of machine.sail.

   machine.sail's IPI is a pure mailbox (`Machine.ipi`, `deliver_ipi`/
   `receive_ipi`): the leader marks core i's delivered bit and the remote only
   flushes once delivered (S2.3, hardware/rocq/ipi.v).  intc.sail models the
   *device* that produces those bits — a GIC-SGI / RISC-V-AIA-IPI subset with
   the three stages of a real controller:

     - `intc_send`   — the originator's MMIO write (GICD_SGIR / the per-hart
                       IPI address / IMSIC setipnum); the distributor latches
                       the per-core pending line ("generated by a write to an
                       SGI register in the GIC", IHI0069 2.1.2; "a machine
                       with multiple harts must provide for each hart an
                       implementation-defined memory address that can be
                       written to signal a machine-level software interrupt",
                       riscv-aia IPIs.adoc).
     - `intc_mask`/`intc_unmask` — GICD_ISENABLER0/ICENABLER0 (or mie.MSIE);
                       a masked interrupt stays pending but is not signalled.
     - `intc_ack`    — the PE reads its interrupt (ICC_IAR / mip): if pending
                       and unmasked, the pending state is cleared *for that PE*
                       (IHI0069 2.1.2) and the doorbell rings — ipi[i] := true.

   What is proved here:

   1. **The doorbell only rings on ack** — `intc_send_preserves_ipi`; and the
      pending line is latched by send (`intc_send_sets_pending`).
   2. **Masking** — a masked ack is a spurious no-op (`intc_ack_masked_noop`:
      the interrupt is held pending, nothing is delivered); unmasking then
      acking delivers (`intc_unmask_then_ack_delivers`).
   3. **Reification** — `intc_send_ack_refines_deliver_ipi`: when the
      controller's mailbox agrees with `Machine.ipi`, one send+ack performs
      exactly `deliver_ipi`'s update (the bridge lemmas
      `intc_set_bit_eq_list_update_bool`/`intc_get_bit_eq_list_nth_bool` make
      the two list encodings literally equal).
   4. **Delivery precedes ack, by construction** — `intc_delivery_enables_receive_ipi`
      composes (3) with ipi.v's `receive_ipi_after_delivery_sfences`: a machine
      whose mailbox was produced by the interrupt controller flushes exactly
      core i on `receive_ipi`.

   See doc/system-state-goals.md (SSG-3) and doc/interrupt-controller.md. *)

